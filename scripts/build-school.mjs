/** Bundle readable, dependency-free Campus sources for the static browser distribution. */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { splitSQL } from "../apps/studio/database/sql-script.mjs";
const root = new URL("../fixtures/campus/", import.meta.url),
  files = {},
  binary = {};
async function walk(url, prefix = "") {
  // Use code-unit ordering instead of localeCompare: ICU versions and locales
  // differ between Windows and GitHub's Linux runner, which made --check fail
  // for an otherwise unchanged Campus fixture.
  for (const entry of (await readdir(url, { withFileTypes: true })).sort(
    (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0),
  )) {
    const path = prefix + entry.name,
      source = new URL(entry.name + (entry.isDirectory() ? "/" : ""), url);
    if (entry.isDirectory()) await walk(source, path + "/");
    else if (/\.(png|jpe?g)$/i.test(path))
      binary[path] = (await readFile(source)).toString("base64");
    else files[path] = await readFile(source, "utf8");
  }
}
await walk(root);
files["data/seed.json"] = JSON.stringify(
  splitSQL(files["database/schema.sql"]).map((sql) =>
    sql.replace(/^(?:\s*--[^\n]*(?:\n|$))+/, "").trim(),
  ),
  null,
  2,
);
const output =
  "// Generated by scripts/build-school.mjs from fixtures/campus/. Edit the source files.\nexport const files = " +
  JSON.stringify(files, null, 2) +
  ";\nconst binary = " +
  JSON.stringify(binary, null, 2) +
  ";\nfor (const [path, content] of Object.entries(binary)) files[path] = Uint8Array.from(atob(content), char => char.charCodeAt(0));\n";
const target = new URL("../apps/studio/school-demo.mjs", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw Error(
      "Campus bundle out of date. Run node scripts/build-school.mjs.",
    );
} else await writeFile(target, output);
console.log(
  "Campus:",
  Object.keys(files).length + Object.keys(binary).length,
  "files",
);
